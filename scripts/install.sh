#!/bin/bash
# Install the FigCraft launcher for DeepSeek Harness on macOS or Linux.
#
#   ./scripts/install.sh                 wrappers, reuse an existing CLI
#   ./scripts/install.sh --with-cli      macOS: also download figcraft-cli
#   ./scripts/install.sh --app PATH      AppImage or non-standard app path
#   ./scripts/install.sh --cli PATH      non-standard figcraft-cli path
#   ./scripts/install.sh --version 0.18.1
#   ./scripts/install.sh --prefix ~/bin
#
# Linux desktop packages (.deb, .rpm, .pkg.tar.zst) already contain
# figcraft-cli, so --with-cli is macOS-only.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREFIX="${PREFIX:-$HOME/.local/bin}"
VERSION="${FIGCRAFT_CLI_VERSION:-0.18.1}"
WITH_CLI=0
APP_PATH=""
CLI_PATH=""

usage() {
  cat <<'EOF'
Install the FigCraft launcher for DeepSeek Harness.

Options:
  --with-cli         macOS only: download figcraft-cli after installing wrappers.
  --version VERSION  FigCraft release to use (default: 0.18.1).
  --prefix DIR       Install wrappers here (default: ~/.local/bin).
  --app PATH         App path for an AppImage or non-standard install.
  --cli PATH         Path to figcraft-cli.
  -h, --help         Show this help.
EOF
}

absolute_path() {
  case "$1" in
    /*) printf '%s\n' "$1" ;;
    *) printf '%s/%s\n' "$(pwd)" "$1" ;;
  esac
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --with-cli)
      WITH_CLI=1
      ;;
    --version)
      [ "$#" -ge 2 ] || { printf 'Missing value for --version\n' >&2; exit 2; }
      VERSION="$2"
      shift
      ;;
    --version=*)
      VERSION="${1#*=}"
      ;;
    --prefix)
      [ "$#" -ge 2 ] || { printf 'Missing value for --prefix\n' >&2; exit 2; }
      PREFIX="$2"
      shift
      ;;
    --prefix=*)
      PREFIX="${1#*=}"
      ;;
    --app)
      [ "$#" -ge 2 ] || { printf 'Missing value for --app\n' >&2; exit 2; }
      APP_PATH="$2"
      shift
      ;;
    --app=*)
      APP_PATH="${1#*=}"
      ;;
    --cli)
      [ "$#" -ge 2 ] || { printf 'Missing value for --cli\n' >&2; exit 2; }
      CLI_PATH="$2"
      shift
      ;;
    --cli=*)
      CLI_PATH="${1#*=}"
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      printf 'Unknown option: %s\n' "$1" >&2
      usage >&2
      exit 2
      ;;
  esac
  shift
done

SYSTEM="$(uname -s)"
case "$SYSTEM" in
  Darwin|Linux)
    ;;
  *)
    printf 'This installer supports macOS and Linux.\n' >&2
    printf 'On Windows, run: powershell -ExecutionPolicy Bypass -File .\\scripts\\install.ps1\n' >&2
    exit 1
    ;;
esac

if [ "$WITH_CLI" -eq 1 ] && [ "$SYSTEM" != "Darwin" ]; then
  printf -- '--with-cli is for macOS only. Linux .deb, .rpm and .pkg.tar.zst packages include figcraft-cli.\n' >&2
  printf 'Install FigCraft from the release first, or point --app/--cli at an existing install.\n' >&2
  exit 1
fi

if [ -n "$APP_PATH" ]; then
  APP_PATH="$(absolute_path "$APP_PATH")"
  if [ ! -x "$APP_PATH" ] && [ ! -d "$APP_PATH" ]; then
    printf 'Not found or not executable: %s\n' "$APP_PATH" >&2
    exit 1
  fi
fi

if [ -n "$CLI_PATH" ]; then
  CLI_PATH="$(absolute_path "$CLI_PATH")"
  if [ ! -x "$CLI_PATH" ]; then
    printf 'Not executable: %s\n' "$CLI_PATH" >&2
    exit 1
  fi
fi

mkdir -p "$PREFIX"
for file in figcraft-mcp figcraft-session figcraft-session-macos figcraft-session-linux; do
  install -m 755 "$ROOT/bin/$file" "$PREFIX/$file"
done
printf 'Installed launchers in %s\n' "$PREFIX"

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/dsh-figcraft"
mkdir -p "$CONFIG_DIR"
install -m 644 "$ROOT/shell/figcraft.sh" "$CONFIG_DIR/aliases.sh"

if [ -n "$APP_PATH" ] || [ -n "$CLI_PATH" ]; then
  {
    printf '# Generated by dsh-figcraft/scripts/install.sh\n'
    if [ -n "$APP_PATH" ]; then
      printf 'export FIGCRAFT_APP=%q\n' "$APP_PATH"
    fi
    if [ -n "$CLI_PATH" ]; then
      printf 'export FIGCRAFT_CLI=%q\n' "$CLI_PATH"
    fi
  } > "$CONFIG_DIR/config"
  printf 'Wrote %s/config\n' "$CONFIG_DIR"
fi

find_cli() {
  local candidate

  if [ -n "$CLI_PATH" ] && [ -x "$CLI_PATH" ]; then
    printf '%s\n' "$CLI_PATH"
    return 0
  fi

  for candidate in \
    "$PREFIX/figcraft-cli" \
    "$HOME/.local/bin/figcraft-cli" \
    /opt/homebrew/bin/figcraft-cli \
    /usr/local/bin/figcraft-cli \
    /usr/bin/figcraft-cli
  do
    if [ -x "$candidate" ]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done

  candidate="$(command -v figcraft-cli 2>/dev/null || true)"
  if [ -n "$candidate" ] && [ -x "$candidate" ]; then
    printf '%s\n' "$candidate"
    return 0
  fi

  if command -v flatpak >/dev/null 2>&1 && flatpak info ai.storyteller.figcraft >/dev/null 2>&1; then
    printf 'flatpak\n'
    return 0
  fi

  return 1
}

find_app() {
  local candidate

  if [ -n "$APP_PATH" ] && [ -x "$APP_PATH" ]; then
    printf '%s\n' "$APP_PATH"
    return 0
  fi

  if [ -x "/Applications/FigCraft.app/Contents/MacOS/FigCraft" ]; then
    printf '%s\n' "/Applications/FigCraft.app"
    return 0
  fi

  for candidate in /usr/bin/figcraft /usr/local/bin/figcraft "$HOME/.local/bin/figcraft"; do
    if [ -x "$candidate" ]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done

  candidate="$(command -v figcraft 2>/dev/null || true)"
  if [ -n "$candidate" ] && [ -x "$candidate" ]; then
    printf '%s\n' "$candidate"
    return 0
  fi

  if command -v flatpak >/dev/null 2>&1 && flatpak info ai.storyteller.figcraft >/dev/null 2>&1; then
    printf 'flatpak\n'
    return 0
  fi

  return 1
}

install_macos_cli() {
  local zip="figcraft-cli-$VERSION-macos-universal.zip"
  local url="https://github.com/storytold/figcraft/releases/download/v$VERSION"
  local data_dir="${XDG_DATA_HOME:-$HOME/.local/share}/figcraft-cli/$VERSION"
  local tmp expected actual

  tmp="$(mktemp -d "${TMPDIR:-/tmp}/dsh-figcraft.XXXXXX")"
  trap 'rm -rf "$tmp"' EXIT

  printf 'Downloading %s (about 90 MB)\n' "$zip"
  curl --fail --location --silent --show-error --retry 3 \
    "$url/$zip" -o "$tmp/$zip"
  curl --fail --location --silent --show-error --retry 3 \
    "$url/SHA256SUMS.txt" -o "$tmp/SHA256SUMS.txt"

  expected="$(awk -v name="$zip" '$2 == name { print $1; exit }' "$tmp/SHA256SUMS.txt")"
  if [ -z "$expected" ]; then
    printf 'No SHA-256 entry for %s in the release checksums.\n' "$zip" >&2
    exit 1
  fi

  actual="$(shasum -a 256 "$tmp/$zip" | awk '{ print $1 }')"
  if [ "$actual" != "$expected" ]; then
    printf 'Checksum mismatch for %s\n' "$zip" >&2
    printf 'expected %s\nactual   %s\n' "$expected" "$actual" >&2
    exit 1
  fi

  unzip -q "$tmp/$zip" -d "$tmp"
  mkdir -p "$data_dir"
  install -m 755 "$tmp/figcraft-cli-$VERSION-macos-universal/figcraft-cli" "$data_dir/figcraft-cli"
  ln -sfn "$data_dir/figcraft-cli" "$PREFIX/figcraft-cli"
  printf 'Installed figcraft-cli %s at %s\n' "$VERSION" "$data_dir/figcraft-cli"
}

print_linux_install_help() {
  local arch os_release command
  local release="https://github.com/storytold/figcraft/releases/latest"

  arch="$(uname -m)"
  case "$arch" in
    arm64|aarch64) arch=aarch64 ;;
    *) arch=x86_64 ;;
  esac

  # Read os-release in a subshell so its VERSION variable cannot clobber ours.
  # shellcheck disable=SC1091
  os_release="$(if [ -r /etc/os-release ]; then . /etc/os-release; fi; printf '%s %s' "${ID:-}" "${ID_LIKE:-}")"

  case " $os_release " in
    *" ubuntu "*|*" debian "*)
      command="sudo apt install ./figcraft-$VERSION-linux-$arch.deb"
      ;;
    *" fedora "*|*" rhel "*|*" centos "*)
      command="sudo dnf install ./figcraft-$VERSION-linux-$arch.rpm"
      ;;
    *" arch "*)
      command="sudo pacman -U ./figcraft-$VERSION-linux-$arch.pkg.tar.zst"
      ;;
    *)
      command=""
      ;;
  esac

  printf '\nFigCraft was not found.\n'
  printf 'Download the Linux package from:\n  %s\n' "$release"
  if [ -n "$command" ]; then
    printf 'Then install it with:\n  %s\n' "$command"
  else
    printf 'Use the .deb, .rpm, .pkg.tar.zst, AppImage, Flatpak or tarball for your distro.\n'
  fi
  printf 'For an AppImage, run this installer again with --app /path/to/FigCraft.AppImage.\n'
}

if [ "$SYSTEM" = "Darwin" ] && [ "$WITH_CLI" -eq 1 ]; then
  install_macos_cli
fi

if cli_path="$(find_cli)"; then
  case "$cli_path" in
    flatpak)
      printf 'Using figcraft-cli from the Flatpak\n'
      ;;
    *)
      printf 'Using figcraft-cli: %s\n' "$cli_path"
      ;;
  esac
else
  case "$APP_PATH" in
    *.AppImage)
      printf 'Using figcraft-cli from the AppImage: %s cli\n' "$APP_PATH"
      ;;
    *)
      if [ "$SYSTEM" = "Darwin" ]; then
        printf 'figcraft-cli not found. Re-run with --with-cli, or install the macOS CLI zip.\n' >&2
      else
        print_linux_install_help
      fi
      ;;
  esac
fi

if app_path="$(find_app)"; then
  printf 'Using FigCraft: %s\n' "$app_path"
fi

if [ "$PREFIX" != "$HOME/.local/bin" ]; then
  printf '\nNote: figcraft-mcp searches ~/.local/bin, Homebrew prefixes and PATH.\n'
  printf 'Put %s on PATH, or set FIGCRAFT_CLI.\n' "$PREFIX"
fi

printf '\nAliases written to %s/aliases.sh\n' "$CONFIG_DIR"
printf 'Add this line to ~/.zshrc or ~/.bashrc:\n'
printf '  source "%s/aliases.sh"\n' "$CONFIG_DIR"
printf 'Then start FigCraft with: figon\n'
